import assert from 'node:assert/strict';
import { registerHooks } from 'node:module';

registerHooks({ resolve(specifier, context, nextResolve) {
  return nextResolve(specifier === 'three' ? new URL('../game/vendor/three.module.min.js', import.meta.url).href : specifier, context);
} });
const THREE = await import('three');
const { createCity } = await import('../game/src/city.js');
const { createPlayer } = await import('../game/src/player.js');
const { createVehicles } = await import('../game/src/vehicles.js');
const { createPedestrians } = await import('../game/src/pedestrians.js');
const { createWanted } = await import('../game/src/wanted.js');
const { createPolice } = await import('../game/src/police.js');
const { createCombat } = await import('../game/src/combat.js');
const { createVisibility } = await import('../game/src/visibility.js');
const scene = new THREE.Scene();
const camera = new THREE.PerspectiveCamera();
const colliders = createCity().userData.colliders;
const player = createPlayer(scene, camera, colliders);
const vehicles = createVehicles(scene, camera, player, colliders);
const pedestrians = createPedestrians(scene, vehicles);
const wanted = createWanted(player.state);
vehicles.onCrime = wanted.crime;
let busted = 0;
const police = createPolice(scene, player, vehicles, colliders, wanted, () => { busted++; wanted.clear(); });
const combat = createCombat(scene, player, vehicles, pedestrians, colliders, wanted);
const tick = (seconds, update) => { for (let frame = 0; frame < Math.ceil(seconds * 60); frame++) update(1 / 60); };
vehicles.interact();
assert.equal(player.state.wanted, 1, 'Theft raises wanted');
wanted.crime(10);
assert.equal(player.state.wanted, 5, 'Five star cap');
tick(20, delta => wanted.update(delta, true));
assert.equal(player.state.wanted, 5, 'Visible heat persists');
tick(12.1, delta => wanted.update(delta, false));
assert.equal(player.state.wanted, 4, 'Hidden heat falls');
tick(49, delta => wanted.update(delta, false));
assert.equal(player.state.wanted, 0, 'Escape clears heat');
wanted.crime(2);
police.update(1 / 60);
const unit = police.units[0];
const startDistance = unit.car.position.distanceTo(player.state.position);
tick(0.5, police.update);
assert(unit.car.position.distanceTo(player.state.position) < startDistance, 'Police chase closes distance');
unit.car.position.copy(player.state.position).add(new THREE.Vector3(0, 0, -4));
vehicles.current.speed = 20;
player.state.speed = 20;
police.update(1 / 60);
assert(vehicles.current.speed < 0 && player.state.health < 100, 'Police rams damage and interrupt car');
vehicles.release();
player.state.speed = 0;
unit.car.position.copy(player.state.position).add(new THREE.Vector3(0, 0, -3));
tick(3.2, police.update);
assert.equal(busted, 1, 'Sustained proximity busts');
police.reset();
assert.equal(police.units.length, 0);
assert(!vehicles.cars.some(car => car.police));
const visible = createVisibility(colliders);
assert(!visible(new THREE.Vector3(-144, 0, -128), new THREE.Vector3(-96, 0, -128)), 'Building blocks sight');
const path = police.route(new THREE.Vector3(-144, 0, -128), new THREE.Vector3(-96, 0, -128));
assert(path.length > 2, 'Police route around real building');
for (let index = 1; index < path.length; index++) assert(visible(path[index - 1], path[index]), 'Route edges clear');
player.state.position.set(-96, 0.4, -128);
player.state.speed = 9;
wanted.crime(2);
police.update(1 / 60);
police.units[0].car.position.set(-144, 0.12, -128);
police.units[0].refresh = 0;
police.units[0].path = [];
const routedCar = police.units[0].car;
tick(7, delta => {
  police.update(delta);
  assert(!colliders.some(bounds => bounds.containsPoint(routedCar.position)), 'Police never drive through buildings');
});
assert(routedCar.position.distanceTo(player.state.position) < 10, `Police complete building detour: ${JSON.stringify(routedCar.position)}`);
police.reset();
wanted.clear();
player.state.position.set(138, 0.4, 50);
player.state.yaw = 0;
const enemy = combat.enemies[0];
assert(combat.attack());
assert.equal(enemy.health, 75, 'Fists hit facing target');
assert(!combat.attack(), 'Attack cooldown enforced');
const health = player.state.health;
tick(1, combat.update);
assert(player.state.health < health, 'Enemy fights back');
combat.switchWeapon();
assert(combat.attack());
assert.equal(player.state.ammo, 11);
assert.equal(enemy.health, 35, 'Pistol damage');
tick(0.3, combat.update);
combat.attack();
assert.equal(enemy.health, 0, 'Non-graphic knockdown');
combat.reload();
assert(!combat.attack(), 'No firing during reload');
tick(1.4, combat.update);
assert.equal(player.state.ammo, 12);
assert.equal(player.state.reserve, 58);
player.state.position.set(-144, 0.4, -128);
player.state.yaw = -Math.PI / 2;
enemy.model.position.set(-96, 0.4, -128);
enemy.health = 100;
combat.attack();
assert.equal(enemy.health, 100, 'Cannot fire through building');
player.state.position.set(144, 0.4, 80);
vehicles.interact();
tick(0.3, combat.update);
assert(!combat.attack(), 'No combat while driving');
vehicles.release();
player.state.recovery = 4;
assert(!combat.attack(), 'No attacks during recovery');
console.log('PASS Phase B: theft, five-star cap, visible/hidden heat, chase, ram, bust, cleanup, city occlusion/routing, fists, retaliation, pistol, cooldown, knockdown, ammo/reload, car/recovery restrictions.');
